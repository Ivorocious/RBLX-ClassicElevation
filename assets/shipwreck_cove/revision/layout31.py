"""Final collision and expert-route revision over the preserved SC30 layout."""
import json, math
from pathlib import Path
import routes30

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / 'layout30.json').read_text())
data['braces'] = []
assets = {}
for file in [ROOT.parent/'phase1/manifest.json', *[ROOT/f'manifest{x}.json' for x in ('13','25','26','27','Horizon27','28','28b','29','30','30b','31c')]]:
    assets.update({a['id']: a for a in json.loads(file.read_text())['assets']})
for asset in assets.values():
    if 'centerBlender' not in asset:
        asset['centerBlender'] = [(asset['boundsBlender']['min'][k]+asset['boundsBlender']['max'][k])/2 for k in range(3)]
old = [s for s in data['surfaces'] if s['section']=='X02']
names = {s['name'] for s in old}
data['surfaces'] = [s for s in data['surfaces'] if s['name'] not in names]
data['placements'] = [p for p in data['placements'] if p['name'] not in names and not p['name'].startswith('SparSupport')]
data['crumble'] = [n for n in data['crumble'] if n not in names]
route = []
for i in range(13):
    t=i/12
    side = (1 if i%2 else -1)*3.0 if i not in (0,12) else 0
    route.append([16+79*t-side*.63, 42.25-25.5*t+(1.1 if i%2 else 0), -91+64*t+side*.78])
new_names=[]
for i,point in enumerate(route):
    name=f'Spar{i:02d}';new_names.append(name)
    yaw=routes30._yaw_x(route,i)+(18 if i%2 else -18)
    pitch=14 if i%2 else -14;roll=30 if i%2 else -30
    size=[3.2,1.88,1.6]
    routes30._asset_landing(data,assets,name,'SC_BrokenSpar',point,size,yaw,'X02',pitch,roll)
    routes30._add_spar_support_frame(data,assets,i,point,yaw,pitch,roll,size)
    data['crumble'].append(name)
chain=['R3_Stern']+new_names+['R4_CaveEntry']
routes30._replace_links(data,names,[chain])
data['testRoutes']['expert_spars']=chain
data['paths']['X02']=[data['checkpoints'][3]]+route+[data['checkpoints'][4]]
for p in data['placements']:
    hull_assets={'R_HullBow_179':'SC_HullClear31Bow','R_HullMid_180':'SC_HullClear31Mid','R_HullStern_181':'SC_HullClear31Stern'}
    if p['name'] in hull_assets:
        p['asset']=hull_assets[p['name']]
    if p['name'] in ('MastYard_083','MastYard_085'):
        p['p'][1] += 3
        p['p'][2] -= 17
    if p['name'] in ('TornSail_084','TornSail_086'):
        old_scale = p['scale'][1]
        p['scale'][1] *= .6
        p['p'][1] += 7.5 - assets[p['asset']]['centerBlender'][2] * old_scale * (.6-1)
        p['p'][2] -= 17
    colors={'CaveMouth26':[220,213,198], 'CaveVault26':[185,201,196], 'CaveSurge26':[162,181,191],
            'R_HullBow_179':[172,169,164], 'R_HullMid_180':[172,169,164], 'R_HullStern_181':[172,169,164]}
    if p['name'] in colors:
        p['tint']=colors[p['name']]
        p['paletteTint']=True
for h in data['falling']:
    if h['kind']=='coconut' and h['top'][0]<-84:
        h['top'][0]=h['bottom'][0]=-82+(int(h['name'].split('_')[-1])%3)
for p in data['placements']:
    if p['name'].startswith('FallingCoconut'):
        h=next(h for h in data['falling'] if h['name']==p['name'])
        p['p']=h['top'].copy()
data['build']='SC_MAP_31'
data['resource']['visuals']=len(data['placements'])
data['resource']['visualTriangles']=sum(assets[p['asset']]['triangles'] for p in data['placements'])
data['resource']['colliders']=len(data['surfaces'])
data['resource']['timberBraces']=len(data['braces'])
def lua(v):
    if isinstance(v,dict):return '{'+','.join('['+json.dumps(str(k))+']='+lua(x) for k,x in v.items())+'}'
    if isinstance(v,list):return '{'+','.join(map(lua,v))+'}'
    if isinstance(v,bool):return 'true' if v else 'false'
    if v is None:return 'nil'
    return json.dumps(v)
(ROOT/'layout31.json').write_text(json.dumps(data,indent=2))
(ROOT/'layout.json').write_text(json.dumps(data,indent=2))
(ROOT.parents[2]/'src/ServerStorage/CourseBuilders/ShipwreckCove/Layout.luau').write_text('-- Generated by assets/shipwreck_cove/revision/layout31.py\nreturn '+lua(data)+'\n')
(ROOT.parents[2]/'src/ServerStorage/CourseBuilders/ShipwreckCove/Kit.luau').write_text('return '+lua(assets)+'\n')
print(data['resource'])
