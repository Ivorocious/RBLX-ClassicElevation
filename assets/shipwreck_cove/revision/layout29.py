# This side ledge suggested bypassing the second wave before reaching checkpoint 5.
obsolete = {'S04_Shore_01', 'ShoreWalk1'}
S[:] = [p for p in S if p['name'] not in obsolete]
data['links'] = [e for e in data['links'] if not any(n in obsolete for n in e)]
P.append(dict(name='WaveExitRock29',asset='SC_R_SeaRockTall',p=[18,-5,79],scale=[1.7,2.4,2.3],yaw=11,section='H02'))
S.append(dict(name='WaveExitBarrier29',p=[18,25,79],size=[13,30,19],yaw=11,section='H02'))

# Retain established palm roots and add a second staggered tier along both sides.
palms = [p for p in P if p['asset']=='SC_R_Palm28']
ground=json.loads((ROOT/'grounding29.json').read_text())
P[:] = [p for p in P if p['asset']!='SC_R_Palm28']
for i in range(10):
    t=(i+.5)/10; side=-1 if i%2 else 1
    x,z=2-94*t,83+47*t
    palms.append(dict(name=f'GrovePalm29_{i}',asset='SC_R_Palm28',p=ground[f'GrovePalm29_{i}'],scale=[1.03,1.22+.11*(i%3),1.03],yaw=i*137.5+47,section='S04_Shore'))
for index,palm in enumerate(palms):
    trunk_scale=list(palm['scale'])
    if palm['name'].startswith('GrovePalm'):
        thickness=.68+.08*(index%4)
        trunk_scale[0]*=thickness;trunk_scale[2]*=thickness
    for asset, suffix in [('SC_R_PalmTrunk29','Trunk'),('SC_R_PalmCrown29','Crown')]:
        p=copy.deepcopy(palm);p['asset']=asset;p['name']=palm['name']+'_'+suffix
        if suffix=='Trunk':p['scale']=trunk_scale
        else:
            lean_offset=2.25*(trunk_scale[0]-palm['scale'][0])
            yaw=math.radians(palm['yaw'])
            p['p'][0]+=math.cos(yaw)*lean_offset;p['p'][2]-=math.sin(yaw)*lean_offset
        p['editGroup']=palm['name'];P.append(p)

data['falling'] = [h for h in data['falling'] if h['kind']!='coconut']
shore_line=[(0,85),(-8,95),(-27,103),(-46,112),(-66,121),(-85,129),(-95,133)]
shore_lengths=[math.dist(a,b) for a,b in zip(shore_line,shore_line[1:])]
def shore_station(t):
    distance=t*sum(shore_lengths)
    for a,b,length in zip(shore_line,shore_line[1:],shore_lengths):
        if distance<=length:
            u=distance/length;dx,dz=b[0]-a[0],b[1]-a[1]
            return a[0]+dx*u,a[1]+dz*u,dz/length,-dx/length
        distance-=length
    a,b=shore_line[-2:];length=shore_lengths[-1]
    return *b,(b[1]-a[1])/length,-(b[0]-a[0])/length
for i in range(24):
    station=i//2;side=-1 if i%2 else 1;t=station/11
    x,z,nx,nz=shore_station(t);x+=nx*side*3.1;z+=nz*side*3.1
    data['falling'].append(dict(name=f'FallingCoconut29_{i}',kind='coconut',top=[x,35+(i%4)*1.4,z],bottom=[x,9.25,z],radius=1.4,visualScale=1.25,period=6.3+(i%5)*.29,warning=1.35,fallTime=.58,hold=.25,phase=i*.713,spread=6.0,seed=729+i))
for i, surge in enumerate(data['surges']): surge['phase']=i*5

