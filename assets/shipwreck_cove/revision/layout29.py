    if 'centerBlender' not in a:a['centerBlender']=[(a['boundsBlender']['min'][k]+a['boundsBlender']['max'][k])/2 for k in range(3)]
    if a['id'].startswith('SC_R_Palm'):a.setdefault('family','vegetation')
