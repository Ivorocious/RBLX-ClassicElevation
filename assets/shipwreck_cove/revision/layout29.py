data = json.loads((ROOT / 'layout28.json').read_text())
assets = {}
for file in [ROOT.parent/'phase1/manifest.json', *[ROOT/f'manifest{x}.json' for x in ('13','25','26','27','Horizon27','28','28b','29')]]:
    assets.update({a['id']: a for a in json.loads(file.read_text())['assets']})
