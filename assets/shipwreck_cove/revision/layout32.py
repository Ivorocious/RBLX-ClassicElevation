"""Solid precision shortcut and inward-facing horizon over the accepted C11 layout."""
import json
from pathlib import Path
import routes30
import mountains32

ROOT=Path(__file__).resolve().parent
data=json.loads((ROOT/'layout31.json').read_text())
assets={}
for file in [ROOT.parent/'phase1/manifest.json',*[ROOT/f'manifest{x}.json' for x in ('13','25','26','27','Horizon27','28','28b','29','30','30b','31c')]]:
    assets.update({a['id']:a for a in json.loads(file.read_text())['assets']})
for a in assets.values():
    if 'centerBlender' not in a:
        a['centerBlender']=[(a['boundsBlender']['min'][k]+a['boundsBlender']['max'][k])/2 for k in range(3)]
old={s['name'] for s in data['surfaces'] if s['section']=='X02'}
data['surfaces']=[s for s in data['surfaces'] if s['name'] not in old]
data['placements']=[p for p in data['placements'] if p['section']!='X02']
data['crumble']=[n for n in data['crumble'] if n not in old]
heights=[42.25,38.7,40.6,34.7,36.7,30.6,32.5,26.4,28.3,21.9,17.0]
route=[]
for i,y in enumerate(heights):
    t=i/(len(heights)-1)
    side=0 if i in (0,10) else (2.8 if i%2 else -2.8)
    route.append([16+79*t-side*.63,y,-91+64*t+side*.78])
names=[]
for i,point in enumerate(route):
    name=f'Spar{i:02d}';names.append(name)
    beam=i%2==0
    incoming=[route[i-1] if i else [0,43,-100],point]
    yaw=routes30._yaw_x(incoming,1)+(12 if i%4==0 else -12) if beam else routes30._yaw_x(route,i)+90
    pitch=10 if beam else 0
    roll=(22 if i%4==0 else -22) if beam else 0
    size=[5.0,1.88,1.15] if beam else [2.35,1.88,2.35]
    routes30._asset_landing(data,assets,name,'SC_BrokenSpar',point,size,yaw,'X02',pitch,roll)
    routes30._add_spar_support_frame(data,assets,i,point,yaw,pitch,roll,size)
for n,i in enumerate((2,6,8)):
    p=route[i]
    data['hazards'].append(dict(name=f'ExpertCrossbar32_{n}',p=[p[0],p[1]+1,p[2]],size=[3.2,.8,.8],section='X02',kind='sweep',period=3.1+n*.25,amplitude=4.2,axis='Z',phase=n*1.05))
chain=['R3_Stern']+names+['R4_CaveEntry']
routes30._replace_links(data,old,[chain])
data['testRoutes']['expert_spars']=chain
data['paths']['X02']=[data['checkpoints'][3]]+route+[data['checkpoints'][4]]
mountains32.apply(data)
data['build']='SC_MAP_32'
data['resource'].update(visuals=len(data['placements']),visualTriangles=sum(assets[p['asset']]['triangles'] for p in data['placements']),colliders=len(data['surfaces']))
def lua(v):
    if isinstance(v,dict):return '{'+','.join('['+json.dumps(str(k))+']='+lua(x) for k,x in v.items())+'}'
    if isinstance(v,list):return '{'+','.join(map(lua,v))+'}'
    if isinstance(v,bool):return 'true' if v else 'false'
    if v is None:return 'nil'
    return json.dumps(v)
(ROOT/'layout32.json').write_text(json.dumps(data,indent=2))
(ROOT/'layout.json').write_text(json.dumps(data,indent=2))
(ROOT.parents[2]/'src/ServerStorage/CourseBuilders/ShipwreckCove/Layout.luau').write_text('-- Generated by assets/shipwreck_cove/revision/layout32.py\nreturn '+lua(data)+'\n')
print(data['resource'])
