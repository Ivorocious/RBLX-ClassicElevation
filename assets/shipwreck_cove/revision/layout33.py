"""Focused wreck-pile, collision and mountain corrections over SC32."""
import json
from pathlib import Path
import mountains33

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / 'layout32.json').read_text())
assets = {}
for file in [ROOT.parent / 'phase1/manifest.json', *ROOT.glob('manifest*.json')]:
    assets.update({a['id']: a for a in json.loads(file.read_text()).get('assets', [])})

data['placements'] = [p for p in data['placements'] if p['section'] != 'X01']
for i, s in enumerate(sorted([s for s in data['surfaces'] if s['section'] == 'X01'], key=lambda s:s['name'])):
    s['size'] = [1.5, .6, 1.75]
    s['pitch'] = 0
    s['roll'] = 12 if i % 2 else -12
    # The cap and collision share one center and rotation; the pile meets its underside.
    import routes30
    offset = routes30._rotated_height_vector(.6, s['yaw'], s['pitch'], s['roll'])
    base = [s['p'][j] - offset[j] for j in range(3)]
    dims = assets['SC_BrokenSpar']['dimensionsRobloxXYZ']
    data['placements'].append(dict(name=s['name'], asset='SC_BrokenSpar', p=base,
        scale=[s['size'][j]/dims[j] for j in range(3)], yaw=s['yaw'], pitch=0,
        roll=s['roll'], section='X01'))
    data['placements'].append(dict(name='WreckPile33_%02d' % i, asset='SC_DockPost',
        p=[base[0], -2, base[2]], scale=[.6, (base[1]+2)/10, .6], yaw=s['yaw'],
        section='X01', platformOwner=s['name']))

for p in data['placements']:
    if p['asset'] == 'SC_R_PalmTrunk29' or p['name'].startswith('LampShelf26_'):
        p['solid'] = True
mountains33.apply(data)
data['build'] = 'SC_MAP_33'
data['resource'].update(visuals=len(data['placements']),
    visualTriangles=sum(assets[p['asset']]['triangles'] for p in data['placements']),
    colliders=len(data['surfaces']))

def lua(v):
    if isinstance(v, dict): return '{'+','.join('['+json.dumps(str(k))+']='+lua(x) for k,x in v.items())+'}'
    if isinstance(v, list): return '{'+','.join(map(lua,v))+'}'
    if isinstance(v, bool): return 'true' if v else 'false'
    if v is None: return 'nil'
    return json.dumps(v)

if __name__ == '__main__':
    for name in ['layout33.json', 'layout.json']:
        (ROOT/name).write_text(json.dumps(data, indent=2))
    (ROOT.parents[2]/'src/ServerStorage/CourseBuilders/ShipwreckCove/Layout.luau').write_text(
        '-- Generated by assets/shipwreck_cove/revision/layout33.py\nreturn '+lua(data)+'\n')
    print(data['resource'])
