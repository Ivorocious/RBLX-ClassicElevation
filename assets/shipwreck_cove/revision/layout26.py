base=runpy.run_path(str(ROOT/'layout.py'))
lua=base['lua'];assets=base['ASSETS']
assets.update({a['id']:a for a in json.loads((ROOT/'manifest26.json').read_text())['assets']})
placements=base['placements'];surfaces=base['surfaces'];links=base['links']
oldstones={p['name'] for p in surfaces if p['section']=='S04_Entry'}
removed={p['name'] for p in placements if p['section'] in ['S04','S04_Entry']}
placements[:]=[p for p in placements if p['name'] not in removed]
surfaces[:]=[p for p in surfaces if p['name'] not in oldstones]
