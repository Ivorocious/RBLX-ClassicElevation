def mesh(asset,name,p,scale=(1,1,1),yaw=0,section='S04'):
    item=dict(asset=asset,name=name,p=list(p),scale=list(scale),yaw=yaw,section=section)
    placements.append(item);return item
for name in ['CaveMouth26','CaveVault26','CaveSurge26']:
    mesh('SC_R_'+name,name,[0,0,0])

