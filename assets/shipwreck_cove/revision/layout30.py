def water_piece(name, asset, position, dimensions, color, yaw=0, amplitude=.10, phase=0, opacity=1):
    size=assets[asset]['dimensionsRobloxXYZ']
    P.append(dict(name=name,asset=asset,p=position,scale=[dimensions[k]/size[k] for k in range(3)],
        yaw=yaw,section='Ocean',tint=color,opacity=opacity,reflectance=.06,
        ocean=dict(amplitude=amplitude,phase=phase,period=7+(phase%4))))

